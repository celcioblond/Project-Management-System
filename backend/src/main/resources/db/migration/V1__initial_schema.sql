-- Application schema. Mirrors the JPA entities in com.celcioblond.pms.model;
-- Hibernate runs with ddl-auto=validate, so any drift fails at startup.

CREATE TABLE users
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    username   VARCHAR(255) NOT NULL UNIQUE,
    age        INTEGER      NOT NULL DEFAULT 0,
    email      VARCHAR(255) NOT NULL UNIQUE,
    password   VARCHAR(255) NOT NULL,
    position   VARCHAR(255),
    department VARCHAR(255),
    role       VARCHAR(255) NOT NULL CHECK (role IN ('ADMIN', 'EMPLOYEE'))
);

CREATE TABLE projects
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL,
    description         VARCHAR(255) NOT NULL,
    type                VARCHAR(255),
    status              VARCHAR(255),
    start_date          TIMESTAMP(6),
    end_date            TIMESTAMP(6),
    created_by_admin_id BIGINT       NOT NULL REFERENCES users (id),
    created_at          TIMESTAMP(6) NOT NULL,
    project_diagram     BYTEA
);

CREATE TABLE project_users
(
    project_id BIGINT NOT NULL REFERENCES projects (id),
    user_id    BIGINT NOT NULL REFERENCES users (id)
);

CREATE TABLE tasks
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                VARCHAR(255) NOT NULL,
    description          VARCHAR(255),
    due_date             TIMESTAMP(6),
    priority             VARCHAR(255),
    status               VARCHAR(255),
    project_id           BIGINT       NOT NULL REFERENCES projects (id),
    assigned_by_admin_id BIGINT       NOT NULL REFERENCES users (id),
    created_at           TIMESTAMP(6)
);

CREATE TABLE task_users
(
    task_id BIGINT NOT NULL REFERENCES tasks (id),
    user_id BIGINT NOT NULL REFERENCES users (id)
);

CREATE TABLE project_comments
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content    VARCHAR(2000) NOT NULL,
    project_id BIGINT        NOT NULL REFERENCES projects (id),
    user_id    BIGINT        NOT NULL REFERENCES users (id),
    created_at TIMESTAMP(6)  NOT NULL,
    updated_at TIMESTAMP(6)
);

CREATE TABLE task_comments
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content    VARCHAR(2000) NOT NULL,
    task_id    BIGINT        NOT NULL REFERENCES tasks (id),
    user_id    BIGINT        NOT NULL REFERENCES users (id),
    created_at TIMESTAMP(6)  NOT NULL,
    updated_at TIMESTAMP(6)
);

-- Foreign keys used in joins and lookups
CREATE INDEX idx_projects_created_by_admin ON projects (created_by_admin_id);
CREATE INDEX idx_project_users_project ON project_users (project_id);
CREATE INDEX idx_project_users_user ON project_users (user_id);
CREATE INDEX idx_tasks_project ON tasks (project_id);
CREATE INDEX idx_task_users_task ON task_users (task_id);
CREATE INDEX idx_task_users_user ON task_users (user_id);
CREATE INDEX idx_project_comments_project ON project_comments (project_id);
CREATE INDEX idx_project_comments_user ON project_comments (user_id);
CREATE INDEX idx_task_comments_task ON task_comments (task_id);
CREATE INDEX idx_task_comments_user ON task_comments (user_id);
